import assert from 'node:assert/strict';
import fs from 'node:fs';
const store=new Map(); globalThis.localStorage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const cache=await import('../src/lib/wordCache.js');
assert.equal(cache.getKnownWordAuthority().phase,'unavailable');
assert.equal(cache.resolveKnownWordState('未知').indeterminate,true);
cache.addManualKnownWord('手動');
assert.equal(cache.resolveKnownWordState('手動').manual,true);
assert.equal(cache.resolveKnownWordState('手動').effective,true);
const request=async(action,{query,notes}={})=>{if(action==='findNotes')return query.includes('Kiku')?[1]:[];if(action==='notesInfo')return notes.map(()=>({fields:{Expression:{value:'既知'}}}));};
await cache.buildCache(request);
assert.equal(cache.getKnownWordAuthority().phase,'ready');
assert.equal(cache.getKnownWordAuthority().complete,true);
assert.equal(cache.resolveKnownWordState('既知').anki,true);
assert.equal(cache.resolveKnownWordState('未知').confirmedUnknown,true);
cache.clearCache();
assert.equal(cache.resolveKnownWordState('未知').confirmedUnknown,false);
assert.equal(cache.resolveKnownWordState('未知').indeterminate,true);
const partial=async(action,{query}={})=>{if(action==='findNotes'&&query.includes('JP1Kv3'))throw new Error('offline subset');return [];};
await cache.buildCache(partial);
assert.equal(cache.getKnownWordAuthority().phase,'partial');
assert.equal(cache.getKnownWordAuthority().complete,false);
assert.equal(cache.resolveKnownWordState('未知').indeterminate,true);
assert.equal(cache.removeManualKnownWord('手動'),true);
const reader=fs.readFileSync('src/components/Reader.jsx','utf8');
for(const token of ['getKnownWordAuthority','resolveKnownWordState','knownWordAuthority','resolveKnownState: resolveKnownWordState'])assert.ok(reader.includes(token));
const learning=fs.readFileSync('src/lib/analyzerLearningModel.js','utf8');assert.ok(learning.includes('knownState.confirmedUnknown'));
console.log('Alpha 4 known-word authority tests passed');
